// ==========================================
// CREATE GAME CARDS
// ==========================================

function createGameCards(list) {

    gamesGrid.innerHTML = "";


    list.forEach(function(game) {

        const card =
            document.createElement("article");


        card.className =
            "library-card";


        card.setAttribute(
            "data-title",
            game.title.toLowerCase()
        );


        card.setAttribute(
            "data-category",
            game.genre.toLowerCase()
        );


        card.innerHTML = `

            <div class="game-image">

                <img
                    src="${game.image}"
                    alt="${game.title}"
                    loading="lazy"
                    onerror="this.style.display='none'"
                >

            </div>


            <div class="game-info">

                <h2>
                    ${game.title}
                </h2>


                <div class="game-meta">

                    ${game.year}
                    •
                    ${game.category}

                </div>


                <button
                    class="view-game"
                    type="button">

                    مشاهده بازی

                </button>

            </div>

        `;


        const viewButton =
            card.querySelector(".view-game");


        viewButton.addEventListener(
            "click",
            function() {

                alert(
                    "صفحه اختصاصی «" +
                    game.title +
                    "» به‌زودی ساخته می‌شود."
                );

            }
        );


        gamesGrid.appendChild(card);

    });


    gameCount.textContent =
        list.length + " بازی";

}


// ==========================================
// FILTER
// ==========================================

let currentFilter = "all";


function filterGames() {

    const text =
        searchBox.value
            .toLowerCase()
            .trim();


    const filtered =
        games.filter(function(game) {

            const title =
                game.title.toLowerCase();


            const genre =
                game.genre.toLowerCase();


            const matchesSearch =
                title.includes(text);


            const matchesFilter =
                currentFilter === "all" ||
                genre.includes(currentFilter);


            return (
                matchesSearch &&
                matchesFilter
            );

        });


    createGameCards(filtered);


    if (filtered.length === 0) {

        noResults.classList.add("show");

    } else {

        noResults.classList.remove("show");

    }

}


// ==========================================
// SEARCH
// ==========================================

if (searchBox) {

    searchBox.addEventListener(
        "input",
        filterGames
    );

}


// ==========================================
// FILTER BUTTONS
// ==========================================

const filterButtons =
    document.querySelectorAll(
        ".filter-button"
    );


filterButtons.forEach(function(button) {

    button.addEventListener(
        "click",
        function() {

            filterButtons.forEach(
                function(btn) {

                    btn.classList.remove(
                        "active"
                    );

                }
            );


            button.classList.add(
                "active"
            );


            currentFilter =
                button.getAttribute(
                    "data-filter"
                );


            filterGames();

        }
    );

});


// ==========================================
// INITIAL LOAD
// ==========================================

createGameCards(games);
